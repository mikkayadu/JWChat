from ingestion.extractors import html_scraper
from ingestion.extractors.html_scraper import _parse_html, scrape_url
from ingestion.utils.preprocessor import preprocess, remove_boilerplate_lines

_URL = "https://www.jw.org/en/bible-teachings/questions/x/"
_FILLER = " ".join(["Suffering was not part of Jehovah God's purpose for mankind."] * 30)


def _page(body):
    return (
        "<html><head><title>Why Do We Suffer?</title></head>"
        f"<body><article id='article'>{body}</article></body></html>"
    )


def _text(body):
    return preprocess(_parse_html(_page(body), _URL, status_code=200)).text


def test_scripture_link_stays_in_its_sentence():
    text = _text(
        f"<p>{_FILLER}</p>"
        '<p>God cannot be tried nor does he himself try anyone." '
        "(<a class='jsBibleLink' href='/en/library/bible/study-bible/books/james/1/'>James 1:13</a>) "
        "Suffering can afflict anyone.</p>"
    )
    assert 'try anyone." (James 1:13) Suffering can afflict anyone.' in text


def test_paragraphs_are_separated_by_blank_lines():
    text = _text(f"<h2>The Bible's answer</h2><p>{_FILLER}</p><p>A second paragraph with several words.</p>")
    assert "## The Bible's answer\n\n" in text
    assert "\n\nA second paragraph with several words." in text


def test_short_scripture_line_survives_boilerplate_filter():
    assert remove_boilerplate_lines("Exodus 20:3\nShare\nPrint") == "Exodus 20:3"


def test_fully_formatted_text_note_is_removed():
    text = "Paul preached in Antioch for a whole year.\n(For fully formatted text, see publication)"
    assert remove_boilerplate_lines(text) == "Paul preached in Antioch for a whole year."


def test_footnote_letters_are_removed():
    text = _text(
        f"<p>{_FILLER}</p>"
        "<p>They committed the original sin.<a class='footnoteLink' href='#footnote1'>a</a> (Genesis 3:6)</p>"
        "<p><a class='fn-symbol' href='#footnotesource1'>a</a> The expression is not in the Bible.</p>"
    )
    assert "original sin. (Genesis 3:6)" in text
    assert "\n\nThe expression is not in the Bible." in text


def test_article_using_error_words_is_kept():
    body = (
        f"<p>{_FILLER}</p>"
        "<p>The terms Mother of God are not found in the Bible. Eve ate the forbidden fruit.</p>"
    )
    assert _parse_html(_page(body), _URL, status_code=200) is not None


def test_short_error_page_is_still_skipped():
    html = (
        "<html><head><title>ERROR: The request could not be satisfied</title></head><body>"
        "<h1>403 ERROR</h1><p>The request could not be satisfied. Request blocked. "
        "Generated by cloudfront (CloudFront).</p></body></html>"
    )
    assert _parse_html(html, _URL, status_code=200) is None


def test_video_player_text_is_removed():
    text = _text(
        f"<p>{_FILLER}</p><div class='video-js vjs-default-skin'>"
        "<div class='vjs-modal-dialog'>This is a modal window. Beginning of dialog window.</div></div>"
    )
    assert "modal window" not in text


def test_plain_http_is_tried_before_the_browser(monkeypatch):
    def no_browser(url):
        raise AssertionError("the browser must not run when plain HTTP works")

    monkeypatch.setattr(html_scraper, "_fetch_with_httpx", lambda url: (_page(f"<p>{_FILLER}</p>"), 200))
    monkeypatch.setattr(html_scraper, "_fetch_with_playwright", no_browser)
    assert scrape_url(_URL) is not None


def test_browser_is_the_fallback(monkeypatch):
    monkeypatch.setattr(html_scraper, "_fetch_with_httpx", lambda url: None)
    monkeypatch.setattr(html_scraper, "_fetch_with_playwright", lambda url: (_page(f"<p>{_FILLER}</p>"), 200))
    assert scrape_url(_URL) is not None
    assert scrape_url(_URL, use_playwright=False) is None


def test_missing_page_skips_the_browser(monkeypatch):
    def gone(url):
        raise html_scraper._PageGone(404)

    def no_browser(url):
        raise AssertionError("the browser must not run for a page that doesn't exist")

    monkeypatch.setattr(html_scraper, "_fetch_with_httpx", gone)
    monkeypatch.setattr(html_scraper, "_fetch_with_playwright", no_browser)
    assert scrape_url(_URL) is None


def test_article_box_in_aside_is_kept():
    text = _text(
        f"<p>{_FILLER}</p><div class='boxSupplement'><aside><div class='boxContent'>"
        "<p>What history reveals: Nebuchadnezzar carried out massive building projects.</p>"
        "</div></aside></div>"
    )
    assert "Nebuchadnezzar carried out massive building projects" in text
